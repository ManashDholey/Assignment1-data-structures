import asyncio
from math_utils import add, subtract, multiply, divide, modulus, square, cube, power, factorial 
from string_utols import concatenate, to_uppercase, to_lowercase, reverse_string, capitalize_words, count_vowels, count_consonants, count_words, count_characters, is_palindrome, remove_whitespace, remove_punctuation, remove_digits, remove_special_characters   
import shop_package

async def main():
    result_add = await add(5, 3)
    result_subtract = await subtract(5, 3)
    result_multiply = await multiply(5, 3)
    result_divide = await divide(5, 3)
    result_modulus = await modulus(5, 3)
    result_square = await square(5)
    result_cube = await cube(5)
    result_power = await power(5, 3)
    result_factorial = await factorial(5)

    print(f"Addition: {result_add}")
    print(f"Subtraction: {result_subtract}")
    print(f"Multiplication: {result_multiply}")
    print(f"Division: {result_divide}")
    print(f"Modulus: {result_modulus}")
    print(f"Square: {result_square}")
    print(f"Cube: {result_cube}")
    print(f"Power: {result_power}")
    print(f"Factorial: {result_factorial}")
    result_concatenate = await concatenate("Hello", "World")
    result_to_uppercase = await to_uppercase("hello")
    result_to_lowercase = await to_lowercase("HELLO")
    result_reverse_string = await reverse_string("hello")
    result_capitalize_words = await capitalize_words("hello world")
    result_count_vowels = await count_vowels("hello")
    result_count_consonants = await count_consonants("hello")
    result_count_words = await count_words("hello world")
    result_count_characters = await count_characters("hello")
    result_is_palindrome = await is_palindrome("racecar")
    result_remove_whitespace = await remove_whitespace("h e l l o")
    result_remove_punctuation = await remove_punctuation("hello!")
    result_remove_digits = await remove_digits("h3ll0")
    result_remove_special_characters = await remove_special_characters("h@e#l$l%o^")

    print(f"Concatenate: {result_concatenate}")
    print(f"To Uppercase: {result_to_uppercase}")
    print(f"To Lowercase: {result_to_lowercase}")
    print(f"Reverse String: {result_reverse_string}")
    print(f"Capitalize Words: {result_capitalize_words}")
    print(f"Count Vowels: {result_count_vowels}")
    print(f"Count Consonants: {result_count_consonants}")
    print(f"Count Words: {result_count_words}")
    print(f"Count Characters: {result_count_characters}")
    print(f"Is Palindrome: {result_is_palindrome}")
    print(f"Remove Whitespace: {result_remove_whitespace}")
    print(f"Remove Punctuation: {result_remove_punctuation}")
    print(f"Remove Digits: {result_remove_digits}")
    print(f"Remove Special Characters: {result_remove_special_characters}")
    result_total = await shop_package.calculate_total([100, 200, 300])
    result_tax = await shop_package.apply_tax(result_total)

    print(f"Total: {result_total}")
    print(f"Total with Tax: {result_tax}")
    result_discount = await shop_package.apply_discount(result_total, 10)
    print(f"Total after Discount: {result_discount}")
    result_flat_discount = await shop_package.flat_discount(result_total)
    print(f"Total after Flat Discount: {result_flat_discount}")
    result_percentage_discount = await shop_package.percentage_discount(result_total, 15)
    print(f"Total after Percentage Discount: {result_percentage_discount}")
    from datetime import datetime, timedelta
    expiry_date = datetime.now() + timedelta(days=1)
    result_limited_time_discount = await shop_package.limited_time_discount(result_total, 20, expiry_date)
    print(f"Total after Limited Time Discount: {result_limited_time_discount}")
    result_final_total = await shop_package.calculate_total([result_limited_time_discount])
    print(f"Final Total after all Discounts: {result_final_total}")

if __name__ == "__main__":
    asyncio.run(main())

